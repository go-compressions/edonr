package main

import (
	"bytes"
	"fmt"
	"strings"
)

// isa describes one vector instruction set for the multi-buffer kernel: how a
// value is loaded, stored and computed, and the code around the block loop.
// Message words are transposed into a staging area once per group of blocks
// and loaded from there as often as needed, so they never need a spill slot.
type isa struct {
	name    string
	build   string // //go:build line
	nregs   int    // allocatable vector registers 0..nregs-1
	vb      int    // bytes per vector register = 8 * lanes
	lanes   int
	state   string // base register of the state ([16][lanes]uint64)
	scratch string // base register of the staging and spill area
	ld      func(base string, off, r int) string
	st      func(r int, base string, off int) string
	// op prints dst = op(srcs); n is the rotation or constant index.
	op func(k kind, d int, s []int, n int) []string
	// prologue prints the code before the loop (loading arguments, constants);
	// stage the transposition of the next group of blocks into the staging area;
	// advance the code after the body.
	prologue, stage, advance func() []string
	frame                    string // TEXT directive tail, e.g. "$0-40"
	sig                      string // Go signature comment
	fn                       string
}

func (a *isa) kernel(g *prog) (asm []byte, scratch int) {
	stage := 16 * a.vb
	n := len(g.ins)
	uses := make([][]int, n)
	for i, in := range g.ins {
		for _, o := range operands(in) {
			uses[o] = append(uses[o], i)
		}
	}
	nextUse := func(v, after int) int {
		for _, u := range uses[v] {
			if u > after {
				return u
			}
		}
		return 1 << 30
	}
	// state words are reloaded from memory on demand: that is only valid while
	// no store to the state has happened yet
	firstStore := n
	for i, in := range g.ins {
		if in.k == kStoreS && i < firstStore {
			firstStore = i
		}
	}
	for v, us := range uses {
		if g.ins[v].k == kLoadS && len(us) > 0 && us[len(us)-1] > firstStore {
			panic("gen: a state word is read after the first store to the state")
		}
	}
	remat := func(v int) bool { k := g.ins[v].k; return k == kLoadM || k == kLoadS }

	var body []string
	e := func(lines ...string) { body = append(body, lines...) }

	reg := make([]int, n)
	slot := make([]int, n)
	for i := range reg {
		reg[i], slot[i] = -1, -1
	}
	owner := make([]int, a.nregs)
	for i := range owner {
		owner[i] = -1
	}
	nslots, freeSlots := 0, []int{}

	loadInto := func(v, r int) {
		in := g.ins[v]
		switch {
		case in.k == kLoadM:
			e(a.ld(a.scratch, a.vb*in.n, r))
		case in.k == kLoadS:
			e(a.ld(a.state, a.vb*in.n, r))
		default:
			e(a.ld(a.scratch, stage+a.vb*slot[v], r))
		}
	}
	evict := func(r, at int) {
		v := owner[r]
		if v >= 0 && nextUse(v, at) < 1<<30 && !remat(v) && slot[v] < 0 {
			if len(freeSlots) > 0 {
				slot[v], freeSlots = freeSlots[len(freeSlots)-1], freeSlots[:len(freeSlots)-1]
			} else {
				slot[v] = nslots
				nslots++
			}
			e(a.st(r, a.scratch, stage+a.vb*slot[v]))
		}
		if v >= 0 {
			reg[v] = -1
		}
		owner[r] = -1
	}
	grab := func(pinned map[int]bool, at int) int {
		best, bestUse := -1, -1
		for r := 0; r < a.nregs; r++ {
			if pinned[r] {
				continue
			}
			if owner[r] < 0 {
				return r
			}
			if u := nextUse(owner[r], at); u > bestUse {
				best, bestUse = r, u
			}
		}
		evict(best, at)
		return best
	}

	for i, in := range g.ins {
		if in.k == kBarrier {
			continue
		}
		pinned := map[int]bool{}
		ops := operands(in)
		for _, o := range ops {
			if reg[o] >= 0 {
				pinned[reg[o]] = true // an operand in a register is not a victim
			}
		}
		for _, o := range ops {
			if reg[o] < 0 {
				r := grab(pinned, i)
				loadInto(o, r)
				reg[o], owner[r] = r, o
			}
			pinned[reg[o]] = true
		}
		srcs := make([]int, len(ops))
		for j, o := range ops {
			srcs[j] = reg[o]
		}
		if in.k == kStoreS {
			e(a.st(reg[in.a], a.state, a.vb*in.n))
		}
		last := map[int]bool{}
		for _, o := range ops {
			if nextUse(o, i) == 1<<30 {
				last[o] = true
			}
		}
		d := -1
		if in.k != kStoreS {
			for o := range last {
				// the operand's register is the destination's to take
				owner[reg[o]] = -1
				delete(pinned, reg[o])
			}
			d = grab(pinned, i)
		}
		switch in.k {
		case kLoadM, kLoadS:
			loadInto(i, d)
		case kAdd, kAddC, kXor, kXor3, kRot:
			e(a.op(in.k, d, srcs, in.n)...)
		}
		for _, o := range ops {
			if last[o] {
				reg[o] = -1
				if slot[o] >= 0 {
					freeSlots = append(freeSlots, slot[o])
					slot[o] = -1
				}
			}
		}
		if in.k != kStoreS {
			reg[i], owner[d] = d, i
		}
	}

	var out bytes.Buffer
	w := func(lines ...string) {
		for _, l := range lines {
			if strings.HasSuffix(l, ":") {
				fmt.Fprintf(&out, "%s\n", l)
			} else {
				fmt.Fprintf(&out, "\t%s\n", l)
			}
		}
	}
	fmt.Fprintf(&out, "// Code generated by internal/gen; DO NOT EDIT.\n\n%s\n\n#include \"textflag.h\"\n\n%s\n", a.build, a.sig)
	fmt.Fprintf(&out, "TEXT ·%s(SB), NOSPLIT, %s\n", a.fn, a.frame)
	w(a.prologue()...)
	w("loop:")
	w(a.stage()...)
	w(body...)
	w(a.advance()...)
	return out.Bytes(), stage + a.vb*nslots
}

func operands(in instr) []int {
	switch in.k {
	case kAdd, kXor:
		if in.a == in.b {
			return []int{in.a}
		}
		return []int{in.a, in.b}
	case kAddC, kRot, kStoreS:
		return []int{in.a}
	case kXor3:
		return []int{in.a, in.b, in.c}
	}
	return nil
}

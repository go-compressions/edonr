package main

import (
	"bytes"
	"fmt"
	"go/format"
)

// scalarGo prints the program as the Go function (*state).compress.
func scalarGo(g *prog) []byte {
	var b bytes.Buffer
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("// Code generated by internal/gen; DO NOT EDIT.")
	w("")
	w("package edonr")
	w("")
	w(`import "math/bits"`)
	w("")
	w("// compress absorbs one 128-byte block: P = R(P, M) xor P xor swapped(M), with R of")
	w("// Definition 8 expanded into eight quasigroup operations (Table 2.2).")
	w("func (s *state) compress(blk []byte) {")
	w("w := words(blk)")
	for i, in := range g.ins {
		v := vname(i)
		switch in.k {
		case kLoadM:
			w("%s := w[%d]", v, in.n)
		case kLoadS:
			w("%s := s[%d]", v, in.n)
		case kAdd:
			w("%s := %s + %s", v, vname(in.a), vname(in.b))
		case kAddC:
			w("%s := %s + %s", v, vname(in.a), [2]string{"constX", "constY"}[in.n])
		case kXor:
			w("%s := %s ^ %s", v, vname(in.a), vname(in.b))
		case kXor3:
			w("%s := %s ^ %s ^ %s", v, vname(in.a), vname(in.b), vname(in.c))
		case kRot:
			w("%s := bits.RotateLeft64(%s, %d)", v, vname(in.a), in.n)
		case kStoreS:
			w("s[%d] = %s", in.n, vname(in.a))
		case kBarrier:
			// A store to the scratch word: the compiler cannot share the
			// loads that follow with those before it, so it reloads instead
			// of keeping the words live (and spilled) across the block.
			w("s[16] = 0")
		}
	}
	w("}")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return out
}

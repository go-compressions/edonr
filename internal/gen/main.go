// Command gen writes the compression kernels of package edonr from one
// dataflow description of the function (ir.go): the scalar Go function, and
// the multi-buffer kernels for NEON (2 messages at a time), AVX2 (4) and
// AVX-512 (8). The many 5-term sums and 3-term xors of the quasigroup
// operation share their partial results (see cse.go), which removes about half
// of the additions of a literal transcription.
//
//	go run ./internal/gen        (from the repository root)
package main

import (
	"fmt"
	"go/format"
	"os"
)

func write(name string, data []byte) {
	if err := os.WriteFile(name, data, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func sizes(build string, consts map[string]int, order []string) []byte {
	s := fmt.Sprintf("// Code generated by internal/gen; DO NOT EDIT.\n\n%s\n\npackage edonr\n\n", build)
	for _, k := range order {
		s += fmt.Sprintf("// %s is the size of the staging and spill area of its kernel.\nconst %s = %d\n\n", k, k, consts[k])
	}
	out, err := format.Source([]byte(s))
	if err != nil {
		panic(err)
	}
	return out
}

func main() {
	write("edonr_compress.go", scalarGo(buildCompress(false)))

	asm, n := neon().kernel(buildCompress(true))
	write("edonr_neon_arm64.s", asm)
	write("edonr_neon_arm64_size.go", sizes("//go:build arm64 && !purego", map[string]int{"neonScratch": n}, []string{"neonScratch"}))

	a2, n2 := avx2().kernel(buildCompress(false))
	write("edonr_avx2_amd64.s", a2)
	a5, n5 := avx512().kernel(buildCompress(true))
	write("edonr_avx512_amd64.s", a5)
	write("edonr_x86_amd64_size.go", sizes("//go:build amd64 && !purego", map[string]int{"avx2Scratch": n2, "avx512Scratch": n5}, []string{"avx2Scratch", "avx512Scratch"}))
}

// Command gen writes the compression kernels of package edonr from one
// dataflow description of the function (ir.go): the scalar Go function, and
// the NEON assembly for two messages at a time. The many 5-term sums and
// 3-term xors of the quasigroup operation share their partial results (see
// cse.go), which removes about half of the additions of a literal
// transcription.
//
//	go run ./internal/gen        (from the repository root)
package main

import (
	"fmt"
	"os"
)

func write(name string, data []byte) {
	if err := os.WriteFile(name, data, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func main() {
	write("edonr_compress.go", scalarGo(buildCompress(false)))
	asm, scratch := neonKernel(buildCompress(true))
	write("edonr_neon_arm64.s", asm)
	write("edonr_neon_arm64_size.go", []byte(fmt.Sprintf(`// Code generated by internal/gen; DO NOT EDIT.

//go:build arm64 && !purego

package edonr

// neonScratch is the size of the staging and spill area of compress2.
const neonScratch = %d
`, scratch)))
}
